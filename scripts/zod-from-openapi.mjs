// Emits Zod (v4) schemas for the named OpenAPI component schemas and everything they reference.
// Usage: node scripts/zod-from-openapi.mjs openapi.json Name... > schemas.ts
import { readFileSync } from "node:fs";

const [file, ...roots] = process.argv.slice(2);
const schemas = JSON.parse(readFileSync(file, "utf8")).components.schemas;
const order = [];
const seen = new Set();

const refName = (r) => r.split("/").pop();
function visit(name) {
  if (seen.has(name)) return;
  seen.add(name);
  walk(schemas[name]);
  order.push(name);
}
function walk(s) {
  if (!s || typeof s !== "object") return;
  if (s.$ref) return visit(refName(s.$ref));
  for (const v of Object.values(s)) if (Array.isArray(v)) v.forEach(walk); else walk(v);
}
roots.forEach(visit);

const lit = (v) => JSON.stringify(v);
function gen(s) {
  if (s.$ref) return refName(s.$ref);
  if (s.const !== undefined) return `z.literal(${lit(s.const)})`;
  if (s.enum) return `z.enum([${s.enum.map(lit).join(", ")}])`;
  if (s.anyOf || s.oneOf) {
    const parts = (s.anyOf ?? s.oneOf).filter((p) => p.type !== "null");
    const nullable = parts.length < (s.anyOf ?? s.oneOf).length;
    const inner = parts.length === 1 ? gen(parts[0]) : `z.union([${parts.map(gen).join(", ")}])`;
    return nullable ? `${inner}.nullable()` : inner;
  }
  switch (s.type) {
    case "string": {
      let o = "z.string()";
      if (s.minLength !== undefined) o += `.min(${s.minLength})`;
      if (s.maxLength !== undefined) o += `.max(${s.maxLength})`;
      return o;
    }
    case "integer":
    case "number": {
      let o = s.type === "integer" ? "z.number().int()" : "z.number()";
      if (s.minimum !== undefined) o += `.min(${s.minimum})`;
      if (s.exclusiveMinimum !== undefined) o += `.gt(${s.exclusiveMinimum})`;
      if (s.maximum !== undefined) o += `.max(${s.maximum})`;
      if (s.exclusiveMaximum !== undefined) o += `.lt(${s.exclusiveMaximum})`;
      return o;
    }
    case "boolean": return "z.boolean()";
    case "array": {
      let o = `z.array(${gen(s.items)})`;
      if (s.minItems !== undefined) o += `.min(${s.minItems})`;
      if (s.maxItems !== undefined) o += `.max(${s.maxItems})`;
      return o;
    }
    case "object": {
      const req = new Set(s.required ?? []);
      const props = Object.entries(s.properties ?? {}).map(([k, v]) => `  ${lit(k)}: ${gen(v)}${req.has(k) ? "" : ".optional()"},`);
      return `z.object({\n${props.join("\n")}\n})`;
    }
    default: throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
  }
}

let out = `// Generated by scripts/zod-from-openapi.mjs from openapi.json (make codegen). Do not edit.\nimport { z } from "zod";\n`;
for (const name of order) out += `\nexport const ${name} = ${gen(schemas[name])};\nexport type ${name} = z.infer<typeof ${name}>;\n`;
process.stdout.write(out);
